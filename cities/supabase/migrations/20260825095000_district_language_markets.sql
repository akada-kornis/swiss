  code text primary key, canton char(2) not null, name text not null,
  source text not null default '', updated_at timestamptz not null default now(),
  unique(canton,name)
);
alter table public."Gemeinde" add column if not exists bezirk_code text references public."Bezirk"(code) on update cascade on delete set null;
create index if not exists gemeinde_bezirk_idx on public."Gemeinde"(bezirk_code);
alter table public."Bezirk" enable row level security;
drop policy if exists public_read_bezirk on public."Bezirk";
create policy public_read_bezirk on public."Bezirk" for select to anon, authenticated using (true);
grant select on public."Bezirk" to anon, authenticated;

